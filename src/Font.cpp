int Font::textWidth(const std::string& text, int scale) {
    // Each glyph is GLYPH_W wide plus a 1-dot space between characters.
    if (text.empty()) return 0;
    int chars = static_cast<int>(text.size());
    return (chars * (GLYPH_W + 1) - 1) * scale;
}

void Font::draw(SDL_Renderer* r, const std::string& text, int x, int y,
                int scale, SDL_Color color) {
    SDL_SetRenderDrawColor(r, color.r, color.g, color.b, color.a);
    const auto& table = glyphs();
    int penX = x;
    for (char raw : text) {
        char c = static_cast<char>(std::toupper(static_cast<unsigned char>(raw)));
        auto it = table.find(c);
        if (it == table.end()) it = table.find(' ');
        const Glyph& glyph = it->second;
        for (int row = 0; row < GLYPH_H; ++row) {
            const char* line = glyph[row];
            for (int col = 0; col < GLYPH_W; ++col) {
                if (line[col] == '#') {
                    SDL_Rect px{penX + col * scale, y + row * scale, scale, scale};
                    SDL_RenderFillRect(r, &px);
                }
            }
        }
        penX += (GLYPH_W + 1) * scale;
    }
}

void Font::drawCentered(SDL_Renderer* r, const std::string& text, int cx, int y,
                        int scale, SDL_Color color) {
    int w = textWidth(text, scale);
    draw(r, text, cx - w / 2, y, scale, color);
}
